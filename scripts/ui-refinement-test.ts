import {_electron as electron} from 'playwright';
import {resolve} from 'node:path';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('artifacts/ui-refinement',{recursive:true});
const app=await electron.launch({args:['.',`--user-data-dir=${resolve('artifacts/ui-refinement/profile-'+Date.now())}`]});
try {
 const page=await app.firstWindow();page.setDefaultTimeout(15000);
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.locator('.canvas-tools').waitFor();
 await page.getByRole('button',{name:'Motion',exact:true}).click();
 assert.equal(await page.locator('.motion-group').count(),5);
 assert.equal(await page.locator('.preset-grid button').count(),30);
 assert.equal(await page.locator('.preset-grid button:disabled').count(),30);
 const selectionHint='Select a layer';
 await page.getByText(selectionHint,{exact:false}).waitFor();
 assert.equal(await page.locator('.motion-preset').first().getAttribute('title'),selectionHint);
 assert.equal(await page.locator('.preset-grid button:disabled').first().getAttribute('aria-description'),selectionHint);
 await page.screenshot({path:'artifacts/ui-refinement/motion-categories.png'});
 const search=page.getByRole('searchbox',{name:'Search motion'});
 await search.fill('fade');assert.equal(await page.locator('.preset-grid button').count(),3);
 await search.fill('zzzz');await page.getByText('No matching presets',{exact:true}).waitFor();
 await search.fill('');
 let state=await page.evaluate(()=>window.pteron.call('state'));const screenId=state.project.screens[0].id;
 const svg='<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1920"><rect data-name="Tile" x="100" y="200" width="500" height="500" fill="#38a4ba"/></svg>';
 await page.evaluate(({revision,screenId,svg})=>window.pteron.call('command',{revision,command:{type:'artwork.import',screenId,svg}}),{revision:state.project.revision,screenId,svg});
 await page.locator('.layers').getByRole('button',{name:'Tile',exact:true}).click();
 await page.getByRole('button',{name:'Motion',exact:true}).click();await search.fill('pulse');
 const playhead=page.getByRole('slider',{name:'Playhead',exact:true});
 await playhead.press('Space');
 await page.getByRole('button',{name:'Pause',exact:true}).waitFor();
 await page.getByRole('button',{name:'Pulse',exact:true}).press('Space');
 await page.getByRole('region',{name:'Transition settings'}).waitFor();
 state=await page.evaluate(()=>window.pteron.call('state'));assert.equal(state.project.screens[0].clips[0].preset,'Pulse');
 assert.equal(await page.getByRole('button',{name:'Pause',exact:true}).count(),0,'Adding a preset should pause playback');
 await page.getByRole('button',{name:'Delete clip',exact:true}).click();
 await page.waitForFunction(async()=>(await window.pteron.call('state')).project.screens[0].clips.length===0);
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 await page.waitForFunction(async()=>(await window.pteron.call('state')).project.screens[0].clips.length===1);
 await page.getByRole('button',{name:'Presets',exact:true}).click();
 await search.fill('');
 await page.screenshot({path:'artifacts/ui-refinement/desktop.png'});
 await page.getByRole('button',{name:'Narration',exact:true}).click();
 await page.getByRole('button',{name:'Add caption',exact:true}).click();
 const draftBadge=page.locator('.caption-draft');
 await draftBadge.waitFor();
 const draftWidth=await draftBadge.evaluate(badge=>badge.offsetWidth);
 await page.getByRole('textbox',{name:'Caption text',exact:true}).fill('A clear caption');
 const start=page.getByRole('spinbutton',{name:'Caption start',exact:true});await start.fill('1');await start.press('Tab');
 await page.waitForFunction(async()=>(await window.pteron.call('state')).project.screens[0].captions[0].draft===false);
 await draftBadge.waitFor({state:'hidden'});
 assert.equal(await draftBadge.evaluate(badge=>badge.offsetWidth),draftWidth,'Confirming the caption preserves the badge slot');
 await page.screenshot({path:'artifacts/ui-refinement/caption-spacing.png'});
 await page.getByRole('button',{name:'Delete caption',exact:true}).press('Space');
 await page.waitForFunction(async()=>(await window.pteron.call('state')).project.screens[0].captions.length===0);
 assert.equal(await page.getByRole('button',{name:'Pause',exact:true}).count(),0);
 await page.getByRole('button',{name:'Motion',exact:true}).click();
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(800,560));
 await page.setViewportSize({width:800,height:560});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('searchbox',{name:'Search motion'}).fill('fade');
 assert.equal(await page.locator('.preset-grid button').count(),3);
 await page.screenshot({path:'artifacts/ui-refinement/compact.png'});
 assert.deepEqual(errors,[]);
 console.log('UI refinement: motion search, keyboard actions, clip undo, caption state, and compact layout passed');
} finally {await app.close();}
