 await settings.click();
 assert.equal(await volume.inputValue(),'100');
 const captionStyle=mix.getByRole('combobox',{name:'Style',exact:true});
 assert.deepEqual(await captionStyle.locator('option').allTextContents(),['Regular','Bold','Italic']);
 assert.equal(await captionStyle.inputValue(),'Bold');
 assert.deepEqual(await mix.getByRole('combobox',{name:'Entrance'}).locator('option').allTextContents(),['None','Fade','Rise','Pop']);
 const dialogBounds=await mix.boundingBox();
 assert.ok(dialogBounds&&dialogBounds.x>=0&&dialogBounds.y>=0&&dialogBounds.x+dialogBounds.width<=800&&dialogBounds.y+dialogBounds.height<=560);
