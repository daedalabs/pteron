 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.setViewportSize({width:800,height:560});
 await page.getByRole('button',{name:'Narration',exact:true}).click();
 const settings=page.getByRole('button',{name:'Narration settings',exact:true});
 const mix=page.getByRole('dialog',{name:'Project narration'});
 const volume=mix.getByRole('spinbutton',{name:'Volume (%)'});
 const mute=mix.getByRole('checkbox',{name:'Mute narration'});
 const audioMix=()=>page.locator('audio').evaluate(element=>({volume:(element as HTMLAudioElement).volume,muted:(element as HTMLAudioElement).muted}));
 assert.deepEqual(await audioMix(),{volume:1,muted:false});
 assert.equal(await page.getByRole('region',{name:'Narration and captions'}).evaluate(panel=>panel.scrollWidth<=panel.clientWidth),true);
 await settings.press('Enter');
 await page.waitForFunction(()=>document.activeElement?.getAttribute('name')==='font');
 await volume.fill('20');
 await page.keyboard.press('Escape');
 await mix.waitFor({state:'hidden'});
