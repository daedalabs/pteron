 await page.getByRole('button',{name:'Play',exact:true}).click();await page.waitForTimeout(600);assert.ok(await page.locator('audio').evaluate(a=>(a as HTMLAudioElement).currentTime)>sourceStart+.4);await page.getByRole('button',{name:'Pause',exact:true}).click();
